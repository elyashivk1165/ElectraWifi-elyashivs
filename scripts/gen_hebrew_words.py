"""Renders the Hebrew words shown on the T-Display-S3 screen into 8-bit alpha
bitmaps (src/hebrew_words.h). TFT_eSPI fonts have no Hebrew glyphs, and the
screen only ever shows a fixed set of words, so pre-rendered bitmaps are the
simplest way to get clean Hebrew text.

Usage:
  python3 scripts/gen_hebrew_words.py path/to/Heebo[wght].ttf

Heebo is available from Google Fonts under the SIL Open Font License 1.1.
Requires Pillow built with libraqm (for right-to-left text).
"""
import sys
from PIL import Image, ImageDraw, ImageFont, features

WORDS = [
    ("COOL", "קירור"),
    ("HEAT", "חימום"),
    ("DRY", "ייבוש"),
    ("FAN", "מאוורר"),
    ("AUTO", "אוטומטי"),
    ("OFF", "כבוי"),
    ("BRAND", "אלקטרה"),
    ("STARTING", "מתחבר..."),
]
SIZES = [("BIG", 40, 700), ("SMALL", 20, 600)]


def render(font, text, top, height):
    # Every word of one size shares the same vertical box, so words drawn at
    # the same y line up on a common baseline.
    probe = ImageDraw.Draw(Image.new("L", (1, 1)))
    left, _, right, _ = probe.textbbox((0, 0), text, font=font, direction="rtl")
    img = Image.new("L", (right - left, height), 0)
    ImageDraw.Draw(img).text((-left, -top), text, font=font, fill=255, direction="rtl")
    return img


def vertical_box(font):
    probe = ImageDraw.Draw(Image.new("L", (1, 1)))
    boxes = [probe.textbbox((0, 0), text, font=font, direction="rtl") for _, text in WORDS]
    top = min(b[1] for b in boxes)
    bottom = max(b[3] for b in boxes)
    return top, bottom - top


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    if not features.check("raqm"):
        sys.exit("Pillow was built without libraqm; Hebrew would render reversed.")

    out = [
        "// Generated by scripts/gen_hebrew_words.py from the Heebo font",
        "// (SIL Open Font License 1.1). Do not edit by hand.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "struct HebrewWord { uint16_t w; uint16_t h; const uint8_t* alpha; };",
        "",
    ]
    for size_name, px, weight in SIZES:
        font = ImageFont.truetype(sys.argv[1], px)
        font.set_variation_by_axes([weight])
        top, height = vertical_box(font)
        for key, text in WORDS:
            img = render(font, text, top, height)
            data = ",".join(str(b) for b in img.tobytes())
            out.append(f"// {text}")
            out.append(f"static const uint8_t HW_{size_name}_{key}_DATA[] = {{{data}}};")
            out.append(f"static const HebrewWord HW_{size_name}_{key} = {{{img.width}, {img.height}, HW_{size_name}_{key}_DATA}};")
    out.append("")
    with open("src/hebrew_words.h", "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
