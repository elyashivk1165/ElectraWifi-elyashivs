"""Renders the words and digits shown on the T-Display-S3 screen into 8-bit
alpha bitmaps (src/hebrew_words.h). TFT_eSPI fonts have no Hebrew glyphs, and
the screen only ever shows a fixed set of words, so pre-rendered bitmaps are
the simplest way to get clean Hebrew text. The big temperature digits are
rendered the same way so they match the words.

Usage:
  python3 scripts/gen_hebrew_words.py path/to/Rubik[wght].ttf

Rubik is available from Google Fonts under the SIL Open Font License 1.1.
Requires Pillow built with libraqm (for right-to-left text).
"""
import sys
from PIL import Image, ImageDraw, ImageFont, features

MODES = [("COOL", "קירור"), ("HEAT", "חימום"), ("DRY", "ייבוש"), ("FAN", "מאוורר"), ("AUTO", "אוטומטי")]
DIGITS = [(str(d), str(d)) for d in range(10)]

# (group name, pixel size, weight, words, is_array)
# Every word of one group shares the same vertical box, so words drawn at the
# same y line up on a common baseline.
GROUPS = [
    ("MODE", 33, 700, MODES + [("BRAND", "אלקטרה")], False),
    ("SMALL", 18, 500, MODES + [("STARTING", "מתחבר...")], False),
    ("OFF", 24, 700, [("OFF", "כבוי")], False),
    ("NIGHT", 26, 700, [("NIGHT", "לילה טוב")], False),
    ("DIG_BIG", 58, 800, DIGITS, True),
    ("DIG_SMALL", 18, 500, DIGITS, True),
    ("DIG_TINY", 11, 500, DIGITS, True),
]


def render(font, text, top, height, direction):
    probe = ImageDraw.Draw(Image.new("L", (1, 1)))
    left, _, right, _ = probe.textbbox((0, 0), text, font=font, direction=direction)
    img = Image.new("L", (right - left, height), 0)
    ImageDraw.Draw(img).text((-left, -top), text, font=font, fill=255, direction=direction)
    return img


def vertical_box(font, words, direction):
    probe = ImageDraw.Draw(Image.new("L", (1, 1)))
    boxes = [probe.textbbox((0, 0), text, font=font, direction=direction) for _, text in words]
    top = min(b[1] for b in boxes)
    bottom = max(b[3] for b in boxes)
    return top, bottom - top


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    if not features.check("raqm"):
        sys.exit("Pillow was built without libraqm; Hebrew would render reversed.")

    out = [
        "// Generated by scripts/gen_hebrew_words.py from the Rubik font",
        "// (SIL Open Font License 1.1). Do not edit by hand.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "struct HebrewWord { uint16_t w; uint16_t h; const uint8_t* alpha; };",
        "",
    ]
    for group, px, weight, words, is_array in GROUPS:
        font = ImageFont.truetype(sys.argv[1], px)
        font.set_variation_by_axes([weight])
        direction = "ltr" if is_array else "rtl"
        top, height = vertical_box(font, words, direction)
        entries = []
        for key, text in words:
            img = render(font, text, top, height, direction)
            name = f"HW_{group}_{key}"
            data = ",".join(str(b) for b in img.tobytes())
            out.append(f"// {text}")
            out.append(f"static const uint8_t {name}_DATA[] = {{{data}}};")
            entries.append(f"{{{img.width}, {img.height}, {name}_DATA}}")
            if not is_array:
                out.append(f"static const HebrewWord {name} = {entries[-1]};")
        if is_array:
            out.append(f"static const HebrewWord HW_{group}[] = {{{', '.join(entries)}}};")
    out.append("")
    with open("src/hebrew_words.h", "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
